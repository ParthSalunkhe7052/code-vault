def _cv_get_hwid():
    """
    Generate robust hardware ID for license validation.
    Uses MAC address and system info for stability.
    """
    try:
        # Get MAC address
        mac = ":".join(_cv_re.findall("..", "%012x" % _cv_uuid.getnode()))
        
        # Combine system info
        info = f"""{_cv_platform.node()}|
                   {_cv_platform.system()}|
                   {_cv_platform.machine()}|
                   {_cv_platform.processor()}|
                   {mac}"""
        return _cv_hash.sha256(info.encode()).hexdigest()[:32]
    except Exception as e:
        # Fallback to basic info
        try:
            info = f"{_cv_platform.node()}|{_cv_platform.system()}|{_cv_platform.machine()}"
            return _cv_hash.sha256(info.encode()).hexdigest()[:32]
        except:
            return "unknown-hwid"

def _cv_get_binary_hash():
    """Calculate SHA-256 hash of current executable for integrity checking."""
    try:
        if getattr(_cv_sys, 'frozen', False):
            path = _cv_sys.executable
        else:
            path = _cv_sys.argv[0]
        
        sha256 = _cv_hash.sha256()
        with open(path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256.update(byte_block)
        return sha256.hexdigest()
    except Exception:
        return None

def _cv_verify_binary_integrity():
    """Verify binary hasn't been tampered with."""
    if not _CV_BINARY_HASH or _CV_BINARY_HASH == "skip":
        return True
    
    try:
        actual_hash = _cv_get_binary_hash()
        if actual_hash and actual_hash != _CV_BINARY_HASH:
            _cv_show_error(
                "Binary Tampered",
                "The executable has been modified or corrupted.",
                "This may indicate tampering. Please re-download the application."
            )
            return False
        return True
    except Exception as e:
        print(f"[CodeVault] Warning: Could not verify binary integrity: {e}")
        return True

