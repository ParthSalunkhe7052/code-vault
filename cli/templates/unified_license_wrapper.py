    # Handle GENERIC_BUILD mode (runtime prompt)
    license_key = _CV_LICENSE_KEY
    if _CV_LICENSE_KEY == "GENERIC_BUILD":
        license_key = _cv_load_or_prompt_license()
    
    hwid = _cv_get_hwid()
    
    # Build validation request
    try:
        import urllib.request
        import urllib.error
        
        nonce = _cv_hash.sha256(str(_cv_time.time()).encode()).hexdigest()[:32]
        
        payload = _cv_json.dumps({
            "license_key": license_key,
            "hwid": hwid,
            "machine_name": _cv_platform.node(),
            "nonce": nonce,
            "timestamp": int(_cv_time.time()),
            "binary_hash": _cv_get_binary_hash()
        }).encode('utf-8')
        
        req = urllib.request.Request(
            _CV_SERVER_URL + "/api/v1/license/validate",
            data=payload,
            headers={"Content-Type": "application/json"},
            timeout=15
        )
        
        with urllib.request.urlopen(req) as resp:
            result = _cv_json.loads(resp.read().decode('utf-8'))
            
            # Verify signature
            if not _cv_validate_signature(result):
                return False
            
            # Protocol v2: Verify response freshness
            issued_at = result.get("issued_at")
            if issued_at:
                import time as _cv_time_pkg
                current_time = int(_cv_time_pkg.time())
                response_age = current_time - issued_at
                if response_age > 300:
                    _cv_show_error("SECURITY ERROR",
                                  "Response expired.",
                                  f"Server response is too old ({response_age}s). Possible replay attack.")
                    return False
                if response_age < -60:
                    _cv_show_error("SECURITY ERROR",
                                  "Response from future.",
                                  "Clock skew detected. Please correct your system time.")
                    return False
            
            # Protocol v2: Require jti for replay protection
            if not result.get("jti"):
                _cv_show_error("SECURITY ERROR",
                              "Missing replay protection.",
                              "Server response missing jti (replay protection ID).")
                return False
            
            if result.get("status") == "valid":
                # Start heartbeat
                _cv_start_heartbeat(license_key, hwid, _CV_HEARTBEAT_INTERVAL, _CV_SESSION_TOKEN)
                
                # Register session release
                _atexit.register(_cv_release_session)
                
                # Save session token
                _CV_SESSION_TOKEN = result.get("variables", {}).get("_cv_session_token")
                
                # Check clock drift and save lease
                server_time = result.get("server_time", result.get("timestamp", int(_cv_time.time())))
                local_time = int(_cv_time.time())
                drift = abs(local_time - server_time)
                
                if drift > _CV_CLOCK_DRIFT_MAX:
                    print(f"[CodeVault] Clock drift detected: {drift}s")
                else:
                    lease = _cv_create_lease(license_key, hwid, server_time)
                    _cv_save_lease(lease)
                
                return True
            else:
                # License invalid
                msg = result.get("message", "License invalid")
                
                # Remove saved license
                try:
                    _cv_Path(_cv_get_license_key_path()).unlink(missing_ok=True)
                    _cv_Path(_cv_get_lease_path()).unlink(missing_ok=True)
                except:
                    pass
                
                _cv_show_error("LICENSE INVALID",
                              "The license key was rejected by the server.",
                              f"Server message: {msg}")
                return False
    
    except Exception as e:
        # Connection failed - try offline lease
        error_msg = str(getattr(e, 'reason', e))
        print(f"[CodeVault] Server unreachable: {error_msg}")
        
        if _CV_LEASE_ENABLED:
            valid, msg = _cv_validate_lease(license_key)
            if valid:
                print(f"[CodeVault] {msg}")
                return True
            else:
                _cv_show_error("OFFLINE - LICENSE REQUIRED",
                              "Cannot validate license offline.",
                              f"{msg}\n\nPlease connect to the internet.")
                return False
        else:
            _cv_show_error("CONNECTION REQUIRED",
                          "This application requires an internet connection.",
                          "Offline mode is not enabled for this build.")
            return False

