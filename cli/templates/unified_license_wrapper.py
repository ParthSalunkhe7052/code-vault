def _cv_get_machine_secret():
    """Generate machine-specific secret for encryption."""
    try:
        info = f"{_cv_platform.node()}|{_cv_platform.machine()}|{_cv_platform.processor()}|CV_SALT_2026"
        return _cv_hash.sha256(info.encode()).digest()
    except:
        return _cv_hash.sha256(b"fallback_secret_key").digest()

def _cv_encrypt_lease(lease_data):
    """Encrypt lease data with AES-256-GCM."""
    try:
        secret = _cv_get_machine_secret()
        data_json = _cv_json.dumps(lease_data).encode('utf-8')
        
        try:
            from cryptography.hazmat.primitives.ciphers.aead import AESGCM
            import secrets as _secrets
            nonce = _secrets.token_bytes(12)
            aesgcm = AESGCM(secret)
            ciphertext = aesgcm.encrypt(nonce, data_json, None)
            return _cv_base64.b64encode(b"AES:" + nonce + ciphertext).decode()
        except ImportError:
            # Cryptography not available
            return None
    except Exception:
        return None

def _cv_decrypt_lease(encrypted_data):
    """Decrypt lease data (AES-256-GCM)."""
    try:
        secret = _cv_get_machine_secret()
        raw = _cv_base64.b64decode(encrypted_data)
        
        if raw.startswith(b"AES:"):
            try:
                from cryptography.hazmat.primitives.ciphers.aead import AESGCM
                nonce = raw[4:16]
                ciphertext = raw[16:]
                aesgcm = AESGCM(secret)
                data_json = aesgcm.decrypt(nonce, ciphertext, None)
                return _cv_json.loads(data_json.decode('utf-8'))
            except:
                return None
        else:
            return None
    except:
        return None

def _cv_create_lease(license_key, hwid, server_time):
    """Create new lease token."""
    return {
        "license_key_hash": _cv_hash.sha256(license_key.encode()).hexdigest(),
        "hwid": hwid,
        "expires_at": server_time + _CV_LEASE_DURATION,
        "server_time": server_time,
        "validated_at": int(_cv_time.time())
    }

def _cv_save_lease(lease_data):
    """Save encrypted lease to file."""
    if not _CV_LEASE_ENABLED:
        return False
    try:
        lease_path = _cv_get_lease_path()
        encrypted = _cv_encrypt_lease(lease_data)
        if encrypted:
            _cv_Path(lease_path).write_text(encrypted, encoding='utf-8')
            return True
    except:
        pass
    return False

def _cv_load_lease():
    """Load and decrypt lease from file."""
    if not _CV_LEASE_ENABLED:
        return None
    try:
        lease_path = _cv_get_lease_path()
        if _cv_Path(lease_path).exists():
            encrypted = _cv_Path(lease_path).read_text(encoding='utf-8').strip()
            return _cv_decrypt_lease(encrypted)
    except:
        pass
    return None

def _cv_validate_lease(license_key):
    """Validate existing lease."""
    if not _CV_LEASE_ENABLED:
        return False, "Offline mode not enabled"
    
    lease = _cv_load_lease()
    if not lease:
        return False, "No lease found"
    
    hwid = _cv_get_hwid()
    current_time = int(_cv_time.time())
    
    if lease.get("hwid") != hwid:
        return False, "HWID mismatch - lease invalid on this machine"
    
    key_hash = _cv_hash.sha256(license_key.encode()).hexdigest()
    if lease.get("license_key_hash") != key_hash:
        return False, "License key mismatch"
    
    expires_at = lease.get("expires_at", 0)
    if current_time > expires_at:
        return False, "Lease expired"
    
    remaining = expires_at - current_time
    hours = remaining // 3600
    mins = (remaining % 3600) // 60
    return True, f"Lease valid ({hours}h {mins}m remaining)"

