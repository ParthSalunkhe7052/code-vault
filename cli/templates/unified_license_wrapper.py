def _cv_start_heartbeat(license_key, hwid, interval, session_token=None):
    """Start background heartbeat thread for floating licenses."""
    try:
        import threading as _threading
        
        def heartbeat_loop():
            while True:
                _cv_time.sleep(interval)
                try:
                    import urllib.request
                    
                    payload_data = {
                        "license_key": license_key,
                        "hwid": hwid,
                        "timestamp": int(_cv_time.time())
                    }
                    # Phase 3: Include session_token for floating license heartbeat
                    if session_token:
                        payload_data["session_token"] = session_token
                    
                    payload = _cv_json.dumps(payload_data).encode('utf-8')
                    
                    req = urllib.request.Request(
                        _CV_SERVER_URL + "/api/v1/license/heartbeat",
                        data=payload,
                        headers={"Content-Type": "application/json"}
                    )
                    
                    with urllib.request.urlopen(req, timeout=10) as resp:
                        pass
                except:
                    pass
        
        t = _threading.Thread(target=heartbeat_loop, daemon=True)
        t.start()
    except:
        pass

def _cv_release_session():
    """Release floating license session on exit."""
    global _CV_SESSION_TOKEN
    if not _CV_SESSION_TOKEN:
        return
    try:
        import urllib.request
        
        hwid = _cv_get_hwid()
        payload = _cv_json.dumps({
            "session_token": _CV_SESSION_TOKEN,
            "hwid": hwid
        }).encode('utf-8')
        
        req = urllib.request.Request(
            _CV_SERVER_URL + "/api/v1/license/release",
            data=payload,
            headers={"Content-Type": "application/json"}
        )
        
        with urllib.request.urlopen(req, timeout=5) as resp:
            pass
    except:
        pass

